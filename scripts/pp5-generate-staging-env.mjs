#!/usr/bin/env node

import { randomBytes } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const TEMPLATE_PATH = 'infra/k8s/staging-secrets-template.yaml'

const RANDOM_32 = new Set([
  'AUTH_SECRET',
  'JANUA_WEBHOOK_SECRET',
  'DHANAM_WEBHOOK_SECRET',
  'COTIZA_WEBHOOK_SECRET',
  'PRAVARA_WEBHOOK_SECRET',
  'FORJ_WEBHOOK_SECRET',
  'TEZCA_WEBHOOK_SECRET',
  'FORTUNA_WEBHOOK_SECRET',
  'JANUA_TELEMETRY_WEBHOOK_SECRET',
  'PHYND_CRM_EVENTS_SECRET',
  'COFORMA_WEBHOOK_SECRET',
  'CEQ_WEBHOOK_SECRET',
  'PHYND_ENGAGEMENT_EVENTS_SECRET',
  'PHYND_CAMPAIGN_IMPORT_SECRET',
  'SELVA_WEBHOOK_SECRET',
  'PHYNDCRM_OUTBOUND_SECRET',
  'KARAFIEL_WEBHOOK_SECRET',
  'PRAVARA_DISPATCH_SECRET',
  'SELVA_DISPATCH_SECRET',
  'PHYND_CRM_PROBE_TOKEN',
])

const RANDOM_48 = new Set(['FEDERATION_API_TOKEN'])

const REQUIRED_OPERATOR_VALUES = new Set([
  'DATABASE_URL',
  'REDIS_URL',
  'AUTH_JANUA_ISSUER',
  'AUTH_JANUA_CLIENT_ID',
  'AUTH_JANUA_CLIENT_SECRET',
  'JANUA_API_URL',
  'JANUA_TELEMETRY_API_URL',
  'DHANAM_API_URL',
  'COTIZA_API_URL',
  'PRAVARA_BASE_URL',
  'SELVA_API_URL',
  'FORJ_API_URL',
  'TEZCA_API_URL',
  'TEZCA_PUBLIC_URL',
  'PRAVARA_API_KEY',
  'KARAFIEL_API_URL',
  'KARAFIEL_API_KEY',
  'RESEND_API_KEY',
  'EMAIL_ALLOWLIST_DOMAINS',
])

function parseArgs(argv) {
  const opts = { output: null, force: false }

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i]
    if (arg === '--force') {
      opts.force = true
      continue
    }

    if (arg === '--output') {
      const value = argv[i + 1]
      if (!value) usage('Missing value for --output')
      opts.output = value
      i += 1
      continue
    }

    usage(`Unknown option: ${arg}`)
  }

  return opts
}

function usage(message) {
  if (message) console.error(`ERROR: ${message}`)
  console.error(`
Usage:
  node scripts/pp5-generate-staging-env.mjs
  node scripts/pp5-generate-staging-env.mjs --output /secure/path/phynd-crm-staging.env

The generated file intentionally leaves provider URLs, DB/Redis URLs, OAuth
clients, Resend, and provider API keys as REPLACE_ME_* values.
`)
  process.exit(message ? 1 : 0)
}

function readTemplateValues() {
  const text = fs.readFileSync(path.join(process.cwd(), TEMPLATE_PATH), 'utf8')
  const values = new Map()
  const regex = /^\s{2}([A-Z][A-Z0-9_]*):\s*"([^"]*)"/gm
  for (const match of text.matchAll(regex)) {
    values.set(match[1], match[2])
  }
  return values
}

function generatedValueFor(key, templateValue) {
  if (RANDOM_32.has(key)) return randomBytes(32).toString('base64')
  if (RANDOM_48.has(key)) return randomBytes(48).toString('base64')
  if (REQUIRED_OPERATOR_VALUES.has(key)) return `REPLACE_ME_${key}`
  return templateValue
}

function renderEnv(values) {
  const lines = [
    '# Generated by scripts/pp5-generate-staging-env.mjs',
    '# Do not commit this file. Replace every REPLACE_ME_* before applying.',
    '',
  ]

  const unresolved = []
  for (const [key, templateValue] of values.entries()) {
    const value = generatedValueFor(key, templateValue)
    if (String(value).startsWith('REPLACE_ME_')) unresolved.push(key)
    lines.push(`${key}=${quoteEnvValue(value)}`)
  }

  lines.push('')
  lines.push(`# Required operator values still to replace: ${unresolved.length}`)
  for (const key of unresolved) lines.push(`# - ${key}`)
  lines.push('')

  return lines.join('\n')
}

function quoteEnvValue(value) {
  const text = String(value)
  if (/^[A-Za-z0-9_./:@+-]*$/.test(text)) return text
  return JSON.stringify(text)
}

function main() {
  const opts = parseArgs(process.argv.slice(2))
  const output = renderEnv(readTemplateValues())

  if (!opts.output) {
    process.stdout.write(output)
    return
  }

  const outputPath = path.resolve(opts.output)
  if (fs.existsSync(outputPath) && !opts.force) {
    throw new Error(`${outputPath} exists; pass --force to overwrite`)
  }

  fs.writeFileSync(outputPath, output, { mode: 0o600, flag: opts.force ? 'w' : 'wx' })
  console.log(`Wrote ${outputPath}`)
}

main()
